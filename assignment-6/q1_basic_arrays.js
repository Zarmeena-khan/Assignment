// Create an array named fruits
let fruits = ["Apple", "Banana", "Mango", "Orange", "Grapes"];

console.log("===== Question 1: Basic Array Methods =====");

// length
console.log("Number of fruits:", fruits.length);

// toString()
console.log("Array as string:", fruits.toString());

// at()
console.log("First fruit (index 0):", fruits.at(0));
console.log("Third fruit (index 2):", fruits.at(2));

// join()
console.log("Fruits joined with ' - ':", fruits.join(" - "));
console.log("Fruits joined with ' | ':", fruits.join(" | "));